import 'package:flutter/material.dart';

extension AppLocalizationContext on BuildContext {
  String tr(String source, [Map<String, Object?> args = const {}]) {
    return localize(source, Localizations.localeOf(this).languageCode, args);
  }
}

String localize(
  String source,
  String languageCode, [
  Map<String, Object?> args = const {},
]) {
  if (languageCode == 'en' &&
      (source == '{count} 条记录' || source == '{count} 个步骤')) {
    final count = args['count'] ?? 0;
    final singular = count == 1 || count == '1';
    if (source == '{count} 条记录') {
      return '$count ${singular ? 'record' : 'records'}';
    }
    return '$count ${singular ? 'step' : 'steps'}';
  }
  var value = languageCode == 'en' ? (_english[source] ?? source) : source;
  for (final entry in args.entries) {
    value = value.replaceAll('{${entry.key}}', '${entry.value ?? ''}');
  }
  return value;
}

